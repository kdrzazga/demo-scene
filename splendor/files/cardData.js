function _cost(white, blue, green, red, black) {
    const cost = {};
    if (white) cost.white = white;
    if (blue) cost.blue = blue;
    if (green) cost.green = green;
    if (red) cost.red = red;
    if (black) cost.black = black;
    return cost;
}

