BasicUpstart2(start)
    .var picture = LoadBinary("wolfrider.kla", BF_KOALA)
    .var music = LoadSid("No_Atari_No_Cry.sid")

start:
    jsr KernalCLR_SCR
    ldx #RED
    stx $d020
    stx $d021

    jsr setup_music

copy_data_loop:
    .for (var i = 0; i < 4; i++){
        lda screenData +256*i, x
        sta 1024 + 256*i, x

        lda screenColorData +256*i, x
        sta $d800 + 256*i, x
    }
    inx
    bne copy_data_loop

    jmp *

draw:
    lda #%00011011 //%00011011
    sta $d011

    lda #%00111000 //least significant bytes 0011 -> screenRamArea = $0c00 //0110 -> $1800
	sta $d018
	lda #11011000
	sta $d016
	lda #%00111011
	sta $d011  //watch value of this cell for potential conflict with graphics display
	lda #RED
	sta $d020
	lda #picture.getBackgroundColor()
	sta $d021
	ldx #0

loop1:
    .for (var i=0; i<4; i++) {
	    	lda colorRam+i*$100,x
	    	sta $d800+i*$100,x
	}
	inx
	bne loop1
    rti

irq1:
    asl $d019   //Interrupt status register
    jsr music.play
    pla
    tay
    pla
    tax
    pla
    dec counter
    lda counter
    cmp #0
    beq draw
rti


setup_music:

     ldx #0
     ldy #0
     lda #music.startSong-1
     jsr music.init
     sei
     lda #<irq1
     sta $0314
     lda #>irq1
     sta $0315
     asl $d019   //Interrupt status register
     lda #%01111011
     sta $dc0d   //Interrupt control and status register.
     lda #%10000001
     sta $d01a   //Interrupt control register
     lda #%00011011 //%00011011
     sta $d011   //Screen control register #1 - watch for conflict with value from line43
     lda #%10000000
     sta $d012   //Raster line to generate interrupt at (bits #0-#7).
     cli
     rts

.print "End main code $" + toHexString(*) + " [" + * + "]"
.print "Size: " + (* - start)
.print "End Code segment $" + toHexString(*) + " [" + * + "]"

