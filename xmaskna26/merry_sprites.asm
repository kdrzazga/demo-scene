.macro SpriteFromRows(rows) {
    .for (var row = 0; row < 21; row++) {
        .for (var column = 0; column < 3; column++) {
            .var value = 0
            .if (row < rows.size()) {
                .var line = rows.get(row)
                .for (var bit = 0; bit < 8; bit++) {
                    .var x = column * 8 + bit
                    .if (x < line.size()) {
                        .if (line.substring(x, x + 1) == "#") {
                            .eval value = value | (1 << (7 - bit))
                        }
                    }
                }
            }
            .byte value
        }
    }
    .byte 0
}

