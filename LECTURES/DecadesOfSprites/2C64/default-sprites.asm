init_sprites:
	ldx #%00000000
petla:	lda sprite_colors, x
	sta $d027, x
	inx
	cpx #$8
	bne petla

    // set sprite pointer index
    // this, multiplied by $40, is the address
    // in this case, the address is $2000
    // $80 * $40 = $2000
	//sprite0:
    lda #$80
    sta $07f8

	//sprite1:
    // $81 * $40 = $2040
    lda #$81
    sta $07f9

	//sprite2:
    // $82 * $40 = $2080
    lda #$82
    sta $07fa
    //sprites3-7:
    sta $07fb
    sta $07fc
    sta $07fd
    sta $07fe
    sta $07ff

	rts

